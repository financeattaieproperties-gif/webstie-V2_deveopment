import assert from 'node:assert/strict';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const modulePath=process.env.PLAYWRIGHT_MODULE;
if (!modulePath) throw new Error('Set PLAYWRIGHT_MODULE to the installed playwright/index.mjs for local browser tests.');
const {chromium}=await import(pathToFileURL(modulePath));
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto('http://127.0.0.1:5175/callcenter/?preview=1');
  await page.getByRole('heading',{name:'Overview',exact:true}).waitFor();
  await page.getByText('Ahmad Rahimi',{exact:true}).first().waitFor();
  fs.mkdirSync('test-results/staff',{recursive:true});
  await page.screenshot({path:'test-results/staff/overview.png',fullPage:true});
  await page.getByRole('button',{name:'New entry',exact:true}).click();
  await page.getByLabel('Customer name',{exact:true}).fill('Preview Customer');
  await page.getByLabel('Phone',{exact:true}).fill('0782222279');
  await page.getByLabel('Requirements',{exact:true}).fill('Three-bedroom family apartment with parking.');
  await page.getByLabel('Next follow-up · Kabul',{exact:true}).fill('2099-01-01T10:00');
  await page.getByRole('button',{name:'Save entry',exact:true}).click();
  await page.locator('dialog').waitFor({state:'detached'});
  await page.getByRole('button',{name:'Customers',exact:true}).click();
  await page.getByRole('heading',{name:'Preview Customer',exact:true}).waitFor();
  await page.getByRole('button',{name:'Follow-ups',exact:true}).click();
  await page.getByRole('button',{name:'Overtime',exact:true}).last().click();
  await page.getByRole('button',{name:'Feedback',exact:true}).first().click();
  const select=page.getByLabel('Outcome',{exact:true});
  assert.equal(await select.locator('option[value="closed"]').count(),0);
  await select.selectOption('lost');
  await page.getByLabel('Reason for loss',{exact:true}).fill('Customer no longer interested.');
  assert.equal(await page.getByLabel('Next follow-up · Kabul',{exact:true}).count(),0);
  await page.getByRole('button',{name:'Submit feedback',exact:true}).click();
  await page.locator('dialog').waitFor({state:'detached'});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Open navigation',exact:true}).click();
  await page.getByRole('button',{name:'My Tasks',exact:true}).click();
  await page.getByRole('heading',{name:'My Tasks',exact:true}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No mobile overflow');
  await page.screenshot({path:'test-results/staff/mobile-tasks.png',fullPage:true});
  assert.equal(await page.locator('.language-toggle').count(),0);
  assert.equal(await page.locator('html').getAttribute('dir'),'ltr');
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:5175/management/?preview=1');
  await page.locator('.language-toggle').click();
  assert.equal(await page.locator('html').getAttribute('dir'),'rtl');
  await page.screenshot({path:'test-results/staff/management-rtl.png',fullPage:true});
  await page.locator('.language-toggle').click();
  await page.getByRole('button',{name:'Assign task',exact:true}).click();
  await page.getByLabel('Task title',{exact:true}).fill('Confirm tomorrow’s appointments');
  await page.getByLabel('Instructions',{exact:true}).fill('Contact each customer and update their attendance status.');
  await page.getByLabel('Assign to',{exact:true}).selectOption('1');
  await page.getByLabel('Deadline · Kabul',{exact:true}).fill('2099-01-02T10:00');
  await page.locator('dialog').getByRole('button',{name:'Assign task',exact:true}).click();
  await page.locator('dialog').waitFor({state:'detached'});
  assert.deepEqual(errors,[]);
  console.log('Browser workflow passed: customer creation, overtime feedback, sales-only closure UI, management assignment, mobile and RTL.');
} finally {await browser.close();}
